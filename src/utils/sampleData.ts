export function getSampleYarnData(): YarnItem[] {
  return RAW_SAMPLE_ROWS.map((row, idx) => computeYarnItem(row, idx + 1));
}

// Generate an Excel workbook and trigger download
export function downloadSampleExcel() {
  const ws = XLSX.utils.json_to_sheet(
    RAW_SAMPLE_ROWS.map((r) => ({
      Supplier: r.supplier,
      Code: r.code,
      'Material Code/ Name': r.material,
      'Monthly Avg.': r.monthlyAvg,
      'Bal. Qty': r.balQty,
      '30 days cons.': r.cons30,
      'EP Order processing time': r.ep,
      'Supplier Manufacturing LT': r.sml,
      'Shipment preparation LT (up to ETD)': r.spl,
      'Shipment TT (ETD to ETA)': r.stt,
      'Clearance & Logistics': r.cl,
      'Shipment Incoming LT': r.sil,
      'Safety Stock MOQ': r.safetyStock,
      'Allocated Confirmed orders': r.allocConfirmed,
      'Allocated projection orders': r.allocProjection,
      Comments: r.comments,
    }))
  );

  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, 'Yarn Allocation');
  XLSX.writeFile(wb, 'Yarn_Allocation_Report_Template.xlsx');
}
